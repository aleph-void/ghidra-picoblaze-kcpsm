#!/usr/bin/env python3
"""Real PicoBlaze programs for the Ghidra-vs-simulator comparison: the opbasm test suite
(test/asm/*.psm4 of github.com/kevinpt/opbasm, MIT). Each program checks itself (assert macros count
errors and write the count to port FF); they exercise the whole instruction set through the opbasm
macro library (arithmetic, BCD, multiply/divide, shifts, stack, strings...).
  real_gen.py <pb3|pb6> <opbasm checkout> <outdir> [program ...]
For every program: assemble (opbasm --m4), run in opbsim, and write <outdir>/real-<arch>.txt
(PbEmuTest cases: code, the final registers/scratchpad/ports of the simulator, the address of the
final loop) plus <outdir>/<name>.hex / .log for the Ghidra import checks.
Programs that read program memory through the simulator's ROM peripheral (ports FA/FB) or use
interrupts are skipped (the model has no such peripheral)."""
import glob, json, os, re, subprocess, sys
arch, src, outd = sys.argv[1:4]
only = sys.argv[4:]
pb6 = arch == 'pb6'
os.makedirs(outd, exist_ok=True)
asmdir = os.path.join(src, 'test', 'asm')
env = dict(os.environ, PYTHONPATH=src)
opbsim = os.environ.get('OPBSIM', 'opbsim')
cases = []
skipped = []
for f in sorted(glob.glob(asmdir + '/*.psm4')):
    name = os.path.basename(f)[:-5]
    if only and name not in only:
        continue
    r = subprocess.run([sys.executable, '-m', 'opbasm', '-6' if pb6 else '-3', '--m4', '-x', '-i', f, '-n', name, '-o', outd],
                       capture_output=True, text=True, env=env, cwd=asmdir)
    if r.returncode:
        skipped.append((name, 'opbasm: ' + (r.stdout + r.stderr).strip().splitlines()[-1][:70]))
        continue
    subprocess.run([sys.executable, '-m', 'opbasm', '-6' if pb6 else '-3', '--m4', '-i', f, '-n', name, '-o', outd],
                   capture_output=True, text=True, env=env, cwd=asmdir)
    text = open(f).read()
    if re.search(r'portROM|portISR|inst\(|string_table|\btable\b|\bstring\b', text):
        skipped.append((name, 'uses the simulator ROM peripheral or interrupts'))
        continue
    if re.search(r'\binput\b', text):
        skipped.append((name, 'reads the simulator counter/loopback peripherals'))
        continue
    sim = subprocess.run([opbsim, '--pb6' if pb6 else '--pb3', f'-m:{outd}/{name}.mem', '-j', '-L:30000000'] + (['-s:256'] if pb6 else []),
                         capture_output=True, text=True, env=os.environ)
    if '{' not in sim.stdout:
        skipped.append((name, 'opbsim failed'))
        continue
    st = json.loads(sim.stdout[sim.stdout.index('{'):])
    if st['termination'] != 'termNormal':
        skipped.append((name, 'simulation ended with ' + st['termination']))
        continue
    log = open(f'{outd}/{name}.log').read()
    m = re.search(r'^\s*\*?\s+terminate\s+([0-9A-F]+)\s', log, re.M)
    if not m:
        skipped.append((name, 'no terminate label'))
        continue
    term = int(m.group(1), 16)
    words = [l.strip() for l in open(f'{outd}/{name}.hex') if l.strip()]
    last = max(i for i, w in enumerate(words) if int(w, 16))
    cases.append((name, words[:last + 1], term + 1, st))
with open(f'{outd}/real-{arch}.txt', 'w') as o:
    o.write('# generated by test/real_gen.py; do not edit\n')
    for name, words, endaddr, st in cases:
        o.write(f'case real_{name}\ncode {" ".join(words)}\nend {endaddr:x}\nsteps {int(st["total_insts"]) * 2 + 1000}\n')
        for i, v in enumerate(st['regs_a']):
            o.write(f'expect s{i:X} {v}\n')
        if pb6:
            for i, v in enumerate(st['regs_b']):
                o.write(f'expect s{i:X}_b {v}\n')
        for i, v in enumerate(st['scratchpad'][:256 if pb6 else 64]):
            o.write(f'expect scratchpad:{i:x} {v}\n')
        o.write(f'expect port_out:ff {st["ports_out"][255]}\n')
        o.write('end\n')
print(f'{arch}: {len(cases)} programs ({", ".join(c[0] for c in cases)}); skipped: {skipped}')
