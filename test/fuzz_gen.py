#!/usr/bin/env python3
"""Random programs for the semantic differential between Ghidra's p-code emulation and the Open
PicoBlaze Simulator (opbsim, MIT):
  fuzz_gen.py <pb3|pb6> <count> <seed> <outdir>
Each program loads random values into the 16 registers and the scratchpad, sets the flags, runs
random ALU/shift/scratchpad/port/stack instructions (forward jumps and conditional/unconditional
calls and returns included; register bank switching and STAR for pb6), copies Z and C into sE/sF
and ends in a jump-to-self. opbasm assembles it, opbsim runs it; <outdir>/cases.txt holds the
code and the simulator's final registers/scratchpad/ports for test/PbEmuTest.java. Needs
OPBASM_SRC and OPBSIM (and LD_LIBRARY_PATH for libpcre.so.1)."""
import json, os, random, subprocess, sys
arch, count, seed, outd = sys.argv[1], int(sys.argv[2]), int(sys.argv[3]), sys.argv[4]
pb6 = arch == 'pb6'
os.makedirs(outd, exist_ok=True)
rnd = random.Random(seed)
env = dict(os.environ, PYTHONPATH=os.environ['OPBASM_SRC'])
opbsim = os.environ.get('OPBSIM', 'opbsim')

TWO = ['add', 'addcy', 'and', 'compare', 'or', 'sub', 'subcy', 'test', 'xor', 'load'] + (['comparecy', 'testcy'] if pb6 else [])
SHIFT = ['sl0', 'sl1', 'slx', 'sla', 'rl', 'sr0', 'sr1', 'srx', 'sra', 'rr']
INTERESTING = [0, 1, 2, 0x0f, 0x10, 0x7f, 0x80, 0x81, 0xfe, 0xff]

def const():
    return rnd.choice(INTERESTING) if rnd.random() < 0.4 else rnd.randrange(256)

def reg():
    return 's%X' % rnd.randrange(14)          # sE and sF capture the flags

def instr(nsub):
    r = rnd.random()
    if r < 0.45:
        m = rnd.choice(TWO)
        return f'{m} {reg()}, ' + (reg() if rnd.random() < 0.4 else f'{const():02X}')
    if r < 0.60:
        return f'{rnd.choice(SHIFT)} {reg()}'
    if r < 0.70:
        a = rnd.randrange(32)
        return rnd.choice([f'store {reg()}, {a:02X}', f'fetch {reg()}, {a:02X}'])
    if r < 0.75:
        p = rnd.randrange(0x10, 0x80)
        return rnd.choice([f'output {reg()}, {p:02X}', f'input {reg()}, {p:02X}'])
    if r < 0.80:
        rr = reg()
        a = rnd.randrange(0x10, 0x20)
        return f'load {rr}, {a:02X}\n store {reg()}, {rr}' if rnd.random() < 0.5 else f'load {rr}, {a:02X}\n fetch {reg()}, {rr}'
    if pb6 and r < 0.86:
        return rnd.choice([f'star {reg()}, {reg()}',
                           f'outputk {const():02X}, {rnd.randrange(1, 16):X}'])
    if nsub and r < 0.95:
        c = rnd.choice(['', 'z, ', 'nz, ', 'c, ', 'nc, '])
        return f'call {c}sub{rnd.randrange(nsub)}'
    return f'load {reg()}, {const():02X}'

def program():
    nsub = rnd.randrange(0, 4)
    L = []
    for i in range(16):
        L.append(f'load s{i:X}, {rnd.randrange(256):02X}')
    for a in range(0, 32):
        if rnd.random() < 0.3:
            L.append(f'store s{rnd.randrange(14):X}, {a:02X}')
    L.append(rnd.choice([f'compare s0, {const():02X}', f'add s1, {const():02X}', f'test s2, {const():02X}']))
    lab = 0
    for _ in range(rnd.randrange(8, 60)):
        if pb6 and rnd.random() < 0.08:
            # a register bank section: straight-line code between REGBANK B and REGBANK A (the bank is a
            # disassembly-time context, so every label and call must see the same bank)
            L.append('regbank b')
            for _ in range(rnd.randrange(1, 6)):
                m = rnd.choice(TWO + ['star'])
                L.append(f'{m} {reg()}, ' + (reg() if rnd.random() < 0.5 or m == 'star' else f'{const():02X}'))
            L.append('regbank a')
        elif rnd.random() < 0.12:
            c = rnd.choice(['z', 'nz', 'c', 'nc', ''])
            skip = rnd.randrange(1, 4)
            L.append(f'jump {c + ", " if c else ""}L{lab}')
            for _ in range(skip):
                L.append(instr(nsub))
            L.append(f'L{lab}:')
            lab += 1
        else:
            L.append(instr(nsub))
    L += ['load sE, 00', 'jump nc, Lc1', 'load sE, 01', 'Lc1:', 'load sF, 00', 'jump nz, Lc2', 'load sF, 01', 'Lc2:']
    L += ['end: jump end']
    for i in range(nsub):
        L.append(f'sub{i}:')
        for _ in range(rnd.randrange(1, 5)):
            L.append(instr(0))
        if rnd.random() < 0.5:
            L.append(rnd.choice(['return z', 'return nz', 'return c', 'return nc']))
        # a subroutine always ends in an unconditional return (the simulator would run on into
        # the empty program memory and wrap around)
        L.append(rnd.choice(['return'] + (['load&return s9, 5A'] if pb6 else [])))
    return '\n'.join(L) + '\n', nsub

ports_in = [rnd.randrange(256) for _ in range(256)]
with open(f'{outd}/cases.txt', 'w') as f:
    f.write('# generated by test/fuzz_gen.py; do not edit\n')
    n = 0
    skipped = 0
    for k in range(count):
        src, _ = program()
        open(f'{outd}/p.psm', 'w').write(src)
        open(f'{outd}/prog{k}.psm', 'w').write(src)
        r = subprocess.run([sys.executable, '-m', 'opbasm', '-3' if not pb6 else '-6', '-i', f'{outd}/p.psm', '-n', 'p',
                            '-o', outd], capture_output=True, text=True, env=env)
        if r.returncode:
            print('opbasm failed:', r.stdout[-300:], r.stderr[-300:]); sys.exit(1)
        # label address of "end"
        lst = open(f'{outd}/p.log').read()
        import re
        m = re.search(r'^\s*([0-9A-F]{3})\s+\S+\s+.*\bend: jump end', lst, re.M)
        # the listing marks the label differently; fall back on the symbol table
        m2 = re.search(r'^\s*end\s+([0-9A-F]+)', lst, re.M)
        subprocess.run([sys.executable, '-m', 'opbasm', '-3' if not pb6 else '-6', '-x', '-i', f'{outd}/p.psm', '-n', 'p',
                        '-o', outd], capture_output=True, text=True, env=env)
        words = [l.strip() for l in open(f'{outd}/p.hex') if l.strip()]
        sim = subprocess.run([opbsim, '--pb6' if pb6 else '--pb3', f'-m:{outd}/p.mem' if False else '-m:%s/p.mem' % outd,
                              '-L:20000', '-j', '-i:' + json.dumps({'00': ports_in})] + (['-s:256'] if pb6 else []), capture_output=True, text=True, env=os.environ)
        if '{' not in sim.stdout:
            print('opbsim failed:', sim.stdout[-300:], sim.stderr[-300:]); sys.exit(1)
        st = json.loads(sim.stdout[sim.stdout.index('{'):])
        if st['termination'] != 'termInstLimit':      # ended before the final loop (stack overflow ...): skip
            skipped += 1
            continue
        # end address = address of the "end" label: first "jump end" instruction that jumps to itself
        endaddr = None
        for i, w in enumerate(words):
            if int(w, 16) == (0x22000 if pb6 else 0x34000) + i:
                endaddr = i
                break
        assert endaddr is not None, 'no end loop'
        used = len([w for w in words if True])
        f.write(f'case fuzz_{arch}_{seed}_{k}\n')
        # only the part up to the last non-zero word matters
        last = max(i for i, w in enumerate(words) if int(w, 16) != 0) if any(int(w, 16) for w in words) else 0
        f.write('code ' + ' '.join(w for w in words[:last + 1]) + '\n')
        f.write(f'end {endaddr:x}\nsteps 20000\n')
        # ports: set every input port (the io space is one memory in the model)
        for i in range(0, 256, 8):
            f.write('set port_in:%x/8 0x%x\n' % (i, int.from_bytes(bytes(ports_in[i:i + 8]), 'big')))
        for i, v in enumerate(st['regs_a']):
            f.write(f'expect s{i:X} {v}\n')
        if pb6:
            for i, v in enumerate(st['regs_b']):
                f.write(f'expect s{i:X}_b {v}\n')
        for i, v in enumerate(st['scratchpad'][:256 if pb6 else 64]):
            f.write(f'expect scratchpad:{i:x} {v}\n')
        f.write('end\n')
        n += 1
print(f'{n} programs written to {outd}/cases.txt ({skipped} skipped: the simulator did not reach the final loop)')
